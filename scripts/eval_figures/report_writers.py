from pathlib import Path

import numpy as np

from .stats_helpers import fmt_p


def write_summary(
    sweep: dict,
    phase3: dict,
    phase4: dict,
    base_acc: dict,
    fa_acc: dict,
    comb_acc: dict,
    out_path: Path,
) -> None:
    p3_t     = phase3["throughput"]
    p3_a     = phase3["accuracy"]
    p4_cvb_t = phase4["combined_vs_baseline"]["throughput"]
    p4_cvb_a = phase4["combined_vs_baseline"]["accuracy"]
    p4_cvf_t = phase4["combined_vs_flash_only"]["throughput"]

    rec_r = sweep.get("recommended_r", 8)
    r4    = next(r for r in sweep["results"] if r["r"] == 4)
    r8    = next(r for r in sweep["results"] if r["r"] == rec_r)

    fa_imp           = p3_t["improvement_pct"]
    comb_vs_base_imp = p4_cvb_t["improvement_pct"]
    comb_vs_fa_imp   = p4_cvf_t["improvement_pct"]

    lines = [
        "# Experimental Evaluation Summary",
        "",
        "> Auto-generated by `scripts/generate_eval_figures.py`",
        "",
        "## Key Findings",
        "",
        f"- **Flash Attention alone: +{fa_imp:.1f}% throughput** over the standard ViT-B/16 "
        f"baseline (p ≈ {p3_t['p_value']:.2e}, highly significant). Accuracy cost is negligible: "
        f"−{abs(p3_a['diff_pct']):.3f} pp (p = {p3_a['p_value']:.3f}, n.s.).",
        "",
        f"- **Token Merging (r={rec_r}) sweet spot: +{r8['throughput_improvement_pct']:.1f}% "
        f"throughput**, −{r8['accuracy_drop_pct']:.3f} pp accuracy. "
        "This is the recommended Pareto-optimal configuration.",
        "",
        f"- **⚠ Negative interaction — Combined (ToMe+FA) is *slower* than FA-alone:** "
        f"adding ToMe on top of Flash Attention reduces throughput by {abs(comb_vs_fa_imp):.1f}% "
        f"relative to FA-only (p = {p4_cvf_t['p_value']:.2e}). "
        "The expected additive speedup does not materialise.",
        "",
        f"- **ToMe r=4 shows a statistically significant slowdown:** "
        f"{r4['throughput_improvement_pct']:+.2f}% (p = {r4['p_value']:.2e}). "
        f"A {r4['reduction_pct']}% token reduction is insufficient to overcome "
        "attention-kernel overhead at this batch size.",
        "",
        f"- **Combined vs. Baseline is still net-positive (+{comb_vs_base_imp:.1f}%, "
        f"p ≈ {p4_cvb_t['p_value']:.2e})**, but the accuracy penalty "
        f"(−{abs(p4_cvb_a['diff_pct']):.3f} pp) is larger than either method alone, "
        "and throughput is dominated by FA-only. Combined is Pareto-inferior.",
        "",
        "- **Memory caveat:** peak GPU memory differences are not statistically significant "
        "across any condition (all p > 0.2). Inter-trial variance is extremely low (< 0.1 GB), "
        "so the null result reflects genuine equivalence, not a power failure.",
        "",
        "## Slide Text",
        "",
        (
            "> *Flash Attention delivers a clean +{fa:.0f}% throughput gain with no measurable "
            "accuracy cost, while Token Merging provides an additional configurable speed–accuracy "
            "trade-off. However, stacking both optimisations yields **less** total speedup than "
            "Flash Attention alone — a statistically significant negative interaction "
            "(p = {p:.2e}) that warns against naïve combination of these techniques.*"
        ).format(fa=fa_imp, p=p4_cvf_t["p_value"]),
        "",
        "## Numeric Reference",
        "",
        "| Condition | Throughput (img/s) | Top-1 Acc (%) | Δ Throughput vs. Baseline | Δ Accuracy vs. Baseline |",
        "|-----------|:-----------------:|:------------:|:------------------------:|:-----------------------:|",
        f"| Baseline           | {p3_t['mean_a']:.0f} | {base_acc['top1_accuracy']*100:.2f} | — | — |",
        f"| ToMe r={rec_r}           | {r8['mean_throughput']:.0f} | {r8['top1_accuracy']*100:.2f} | +{r8['throughput_improvement_pct']:.1f}% | {-r8['accuracy_drop_pct']:+.3f} pp |",
        f"| FA-Only            | {p3_t['mean_b']:.0f} | {fa_acc['top1_accuracy']*100:.2f} | +{fa_imp:.1f}% | {p3_a['diff_pct']:+.3f} pp |",
        f"| Combined (ToMe+FA) | {p4_cvb_t['mean_b']:.0f} | {comb_acc['top1_accuracy']*100:.2f} | +{comb_vs_base_imp:.1f}% | {p4_cvb_a['diff_pct']:+.3f} pp |",
        "",
    ]
    out_path.write_text("\n".join(lines))
    print(f"  [C] Markdown summary   → {out_path}")


def write_ppt_tables(sweep: dict, phase3: dict, phase4: dict, out_dir: Path) -> None:
    rec_r = sweep.get("recommended_r", 8)
    r_rec = next(r for r in sweep["results"] if r["r"] == rec_r)

    def _tp_ci(stat):
        lo = stat["ci_low"]  / stat["mean_a"] * 100
        hi = stat["ci_high"] / stat["mean_a"] * 100
        return f"[{lo:+.3f}, {hi:+.3f}]%"

    def _acc_ci(stat):
        return f"[{stat['ci_low']:+.3f}, {stat['ci_high']:+.3f}]pp"

    rows = [
        {
            "comparison":  "FA-Only vs Baseline",
            "metric":      "Throughput",
            "effect":      f"{phase3['throughput']['improvement_pct']:+.3f}%",
            "ci95":        _tp_ci(phase3["throughput"]),
            "test_stat":   f"t={phase3['throughput']['t_stat']:.3f}",
            "p_value":     fmt_p(phase3["throughput"]["p_value"]),
            "significant": "Yes" if phase3["throughput"]["p_value"] < 0.05 else "No",
        },
        {
            "comparison":  f"ToMe r={rec_r} vs Baseline",
            "metric":      "Throughput",
            "effect":      f"{r_rec['throughput_improvement_pct']:+.3f}%",
            "ci95":        "N/A (not serialized)",
            "test_stat":   f"t={r_rec['t_stat']:.3f}",
            "p_value":     fmt_p(r_rec["p_value_adj"]),
            "significant": "Yes" if r_rec["p_value_adj"] < 0.05 else "No",
        },
        {
            "comparison":  "Combined vs Baseline",
            "metric":      "Throughput",
            "effect":      f"{phase4['combined_vs_baseline']['throughput']['improvement_pct']:+.3f}%",
            "ci95":        _tp_ci(phase4["combined_vs_baseline"]["throughput"]),
            "test_stat":   f"t={phase4['combined_vs_baseline']['throughput']['t_stat']:.3f}",
            "p_value":     fmt_p(phase4["combined_vs_baseline"]["throughput"]["p_value"]),
            "significant": "Yes" if phase4["combined_vs_baseline"]["throughput"]["p_value"] < 0.05 else "No",
        },
        {
            "comparison":  "Combined vs FA-Only",
            "metric":      "Throughput",
            "effect":      f"{phase4['combined_vs_flash_only']['throughput']['improvement_pct']:+.3f}%",
            "ci95":        _tp_ci(phase4["combined_vs_flash_only"]["throughput"]),
            "test_stat":   f"t={phase4['combined_vs_flash_only']['throughput']['t_stat']:.3f}",
            "p_value":     fmt_p(phase4["combined_vs_flash_only"]["throughput"]["p_value"]),
            "significant": "Yes" if phase4["combined_vs_flash_only"]["throughput"]["p_value"] < 0.05 else "No",
        },
        {
            "comparison":  "FA-Only vs Baseline",
            "metric":      "Accuracy",
            "effect":      f"{phase3['accuracy']['diff_pct']:+.3f}pp",
            "ci95":        _acc_ci(phase3["accuracy"]),
            "test_stat":   f"z={phase3['accuracy']['z_stat']:.3f}",
            "p_value":     fmt_p(phase3["accuracy"]["p_value"]),
            "significant": "Yes" if phase3["accuracy"]["p_value"] < 0.05 else "No",
        },
        {
            "comparison":  f"ToMe r={rec_r} vs Baseline",
            "metric":      "Accuracy",
            "effect":      f"{-r_rec['accuracy_drop_pct']:+.3f}pp",
            "ci95":        "N/A (not serialized)",
            "test_stat":   f"z={r_rec['z_stat']:.3f}",
            "p_value":     fmt_p(r_rec["acc_p_value_adj"]),
            "significant": "Yes" if r_rec["acc_p_value_adj"] < 0.05 else "No",
        },
        {
            "comparison":  "Combined vs Baseline",
            "metric":      "Accuracy",
            "effect":      f"{phase4['combined_vs_baseline']['accuracy']['diff_pct']:+.3f}pp",
            "ci95":        _acc_ci(phase4["combined_vs_baseline"]["accuracy"]),
            "test_stat":   f"z={phase4['combined_vs_baseline']['accuracy']['z_stat']:.3f}",
            "p_value":     fmt_p(phase4["combined_vs_baseline"]["accuracy"]["p_value"]),
            "significant": "Yes" if phase4["combined_vs_baseline"]["accuracy"]["p_value"] < 0.05 else "No",
        },
        {
            "comparison":  "Combined vs FA-Only",
            "metric":      "Accuracy",
            "effect":      f"{phase4['combined_vs_flash_only']['accuracy']['diff_pct']:+.3f}pp",
            "ci95":        _acc_ci(phase4["combined_vs_flash_only"]["accuracy"]),
            "test_stat":   f"z={phase4['combined_vs_flash_only']['accuracy']['z_stat']:.3f}",
            "p_value":     fmt_p(phase4["combined_vs_flash_only"]["accuracy"]["p_value"]),
            "significant": "Yes" if phase4["combined_vs_flash_only"]["accuracy"]["p_value"] < 0.05 else "No",
        },
    ]

    out_dir.mkdir(exist_ok=True)
    headers  = ["comparison", "metric", "effect", "ci95", "test_stat", "p_value", "significant"]
    csv_path = out_dir / "stats_summary_for_ppt.csv"
    md_path  = out_dir / "stats_summary_for_ppt.md"

    csv_lines = [",".join(headers)]
    for row in rows:
        csv_lines.append(",".join(f'"{row[h]}"' for h in headers))
    csv_path.write_text("\n".join(csv_lines) + "\n")

    md_lines = [
        "# Statistical Test Summary (PPT-ready)",
        "",
        "| Comparison | Metric | Effect | 95% CI | Test statistic | p-value | Significant (alpha=0.05) |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        md_lines.append(
            f"| {row['comparison']} | {row['metric']} | {row['effect']} "
            f"| {row['ci95']} | {row['test_stat']} | {row['p_value']} | {row['significant']} |"
        )
    md_path.write_text("\n".join(md_lines) + "\n")
    print(f"  [T] PPT tables         → {csv_path} and {md_path}")


def write_project_overview_table(
    base_bench: dict,
    fa_bench: dict,
    comb_bench: dict,
    sweep: dict,
    base_acc: dict,
    fa_acc: dict,
    comb_acc: dict,
    out_dir: Path,
) -> None:
    rec_r = sweep.get("recommended_r", 8)
    r8    = next(r for r in sweep["results"] if r["r"] == rec_r)

    base_t = float(np.mean(np.asarray(base_bench["throughputs"], float)))
    fa_t   = float(np.mean(np.asarray(fa_bench["throughputs"],   float)))
    comb_t = float(np.mean(np.asarray(comb_bench["throughputs"], float)))

    rows = [
        {
            "condition":            "Baseline",
            "throughput_img_s":     f"{base_t:.1f}",
            "top1_acc_pct":         f"{base_acc['top1_accuracy']*100:.2f}",
            "delta_tp_vs_base_pct": "0.0",
            "delta_acc_vs_base_pp": "0.000",
            "takeaway":             "Reference",
        },
        {
            "condition":            f"ToMe r={rec_r}",
            "throughput_img_s":     f"{r8['mean_throughput']:.1f}",
            "top1_acc_pct":         f"{r8['top1_accuracy']*100:.2f}",
            "delta_tp_vs_base_pct": f"{r8['throughput_improvement_pct']:+.1f}",
            "delta_acc_vs_base_pp": f"{-r8['accuracy_drop_pct']:+.3f}",
            "takeaway":             "Best ToMe trade-off",
        },
        {
            "condition":            "FA-Only",
            "throughput_img_s":     f"{fa_t:.1f}",
            "top1_acc_pct":         f"{fa_acc['top1_accuracy']*100:.2f}",
            "delta_tp_vs_base_pct": f"{((fa_t/base_t)-1)*100:+.1f}",
            "delta_acc_vs_base_pp": f"{(fa_acc['top1_accuracy']-base_acc['top1_accuracy'])*100:+.3f}",
            "takeaway":             "Fastest with near-baseline accuracy",
        },
        {
            "condition":            "Combined (ToMe+FA)",
            "throughput_img_s":     f"{comb_t:.1f}",
            "top1_acc_pct":         f"{comb_acc['top1_accuracy']*100:.2f}",
            "delta_tp_vs_base_pct": f"{((comb_t/base_t)-1)*100:+.1f}",
            "delta_acc_vs_base_pp": f"{(comb_acc['top1_accuracy']-base_acc['top1_accuracy'])*100:+.3f}",
            "takeaway":             "Net gain, but below FA-only",
        },
    ]

    out_dir.mkdir(exist_ok=True)
    headers  = [
        "condition", "throughput_img_s", "top1_acc_pct",
        "delta_tp_vs_base_pct", "delta_acc_vs_base_pp", "takeaway",
    ]
    csv_path = out_dir / "project_overview_for_ppt.csv"
    md_path  = out_dir / "project_overview_for_ppt.md"

    csv_lines = [",".join(headers)]
    for row in rows:
        csv_lines.append(",".join(f'"{row[h]}"' for h in headers))
    csv_path.write_text("\n".join(csv_lines) + "\n")

    md_lines = [
        "# Project Overview (PPT-ready)",
        "",
        "| Condition | Throughput (img/s) | Top-1 Acc (%) | Delta Throughput vs Baseline (%) | Delta Accuracy vs Baseline (pp) | Takeaway |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        md_lines.append(
            f"| {row['condition']} | {row['throughput_img_s']} | {row['top1_acc_pct']} "
            f"| {row['delta_tp_vs_base_pct']} | {row['delta_acc_vs_base_pp']} | {row['takeaway']} |"
        )
    md_path.write_text("\n".join(md_lines) + "\n")
    print(f"  [O] Overview tables    → {csv_path} and {md_path}")
